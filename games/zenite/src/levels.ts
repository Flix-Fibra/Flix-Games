// Zênite: A Torre do Sinal - mapas originais das fases 1 (Galpão de Base), 2 (Dutos) e 3 (Servidores).
// Grade: 1 caractere = 1 tile de 16 px. Linha 0 = teto. [linha, coluna] nas ligações.
// Inimigos: cada 'E' ou 'B' recebe, em ordem de leitura (cima->baixo, esq->dir), o tipo da lista enemies.
// Legenda: '#' parede, '=' plataforma vazada, 'H' escada, 'E' inimigo, 'I' item, 'P' início, 'D' porta,
// 'S' repetidora (salva e cura), '^' fio desencapado, 'X' parede rachada (precisa do Impulso), 'B' chefe,
// 'G' ponto de gancho, 'L' alavanca de atalho, 'A' escotilha fechada,
// 'O' e 'o' plataformas de relógio (alternam: quando uma existe a outra some).

export type EnemyType = 'faisca' | 'drone' | 'rato' | 'bobina' | 'pacote' | 'cooler' | 'transformador' | 'matriarca' | 'firewall';

export interface RoomDef {
  id: string;
  name: string;
  width: number;
  height: number;
  tiles: string[];
  enemies: EnemyType[];
}

export interface LinkDef {
  from: string;
  at: [number, number];
  to: string;
  toAt: [number, number];
  /** passagem que só abre depois da alavanca */
  atalho?: boolean;
}

